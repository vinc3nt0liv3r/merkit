using System.Text;

namespace Merkit.Core.Scripts;

/// <summary>
/// Generates stand-alone scripts that apply a prepared DACL with the same safeguards as the app:
/// change detection, backup, WhatIf, read-back verification and automatic rollback.
/// Only the DACL is ever written (never owner, group or SACL).
/// </summary>
public static class ScriptGenerator
{
    public static string PowerShell(string objectDn, string desiredDaclSddl, string expectedCurrentSha256, IEnumerable<string> changeSummary)
    {
        var summary = string.Join("\n", changeSummary.Select(l => "    " + l.Replace("#>", "# >")));
        return PsTemplate
            .Replace("__GENERATED__", DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm 'UTC'"))
            .Replace("__SUMMARY__", summary)
            .Replace("__OU_DN__", objectDn.Replace("'", "''"))
            .Replace("__SHA__", expectedCurrentSha256)
            .Replace("__SDDL__", desiredDaclSddl);
    }

    public static string CSharp(string objectDn, string desiredDaclSddl, string expectedCurrentSha256, IEnumerable<string> changeSummary)
    {
        var summary = string.Join("\n", changeSummary.Select(l => "// " + l));
        return CsTemplate
            .Replace("__GENERATED__", DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm 'UTC'"))
            .Replace("__SUMMARY__", summary)
            .Replace("__OU_DN__", EscapeCs(objectDn))
            .Replace("__SHA__", expectedCurrentSha256)
            .Replace("__SDDL__", EscapeCs(desiredDaclSddl));
    }

    private static string EscapeCs(string s)
    {
        var sb = new StringBuilder();
        foreach (var c in s)
        {
            if (c == '\\' || c == '"') sb.Append('\\');
            sb.Append(c);
        }
        return sb.ToString();
    }

    private const string PsTemplate = @"<#
.SYNOPSIS
    Applies a prepared Active Directory DACL. Generated by Merkit on __GENERATED__.

.DESCRIPTION
    Changes in this script:
__SUMMARY__

    Safeguards: stops if the object changed since Merkit read it, writes a backup first,
    supports -WhatIf, verifies the result and restores the backup automatically on failure.
    Only the DACL is written (not owner, group or SACL). Requires the ActiveDirectory module (RSAT)
    and an account that is allowed to modify permissions on the object.
#>
[CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'High')]
param(
    [string]$TargetDN = '__OU_DN__',
    [string]$BackupDir = (Join-Path $env:ProgramData 'Merkit\Backups'),
    [switch]$IgnoreChanges
)

$ErrorActionPreference = 'Stop'
Import-Module ActiveDirectory

$ExpectedSha256 = '__SHA__'
$DesiredSddl = (@'
__SDDL__
'@).Trim()

function Get-Sha256Hex([string]$Text) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try { ([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($Text))) -replace '-', '').ToLowerInvariant() }
    finally { $sha.Dispose() }
}

function Get-ExplicitRules($Sddl) {
    $sd = New-Object System.DirectoryServices.ActiveDirectorySecurity
    $sd.SetSecurityDescriptorSddlForm($Sddl, [System.Security.AccessControl.AccessControlSections]::Access)
    $sd.GetAccessRules($true, $false, [System.Security.Principal.SecurityIdentifier]) |
        ForEach-Object { '{0}|{1}|{2}|{3}|{4}|{5}|{6}' -f $_.IdentityReference.Value, $_.AccessControlType, [int]$_.ActiveDirectoryRights, $_.InheritanceType, $_.ObjectType, $_.InheritedObjectType, $_.PropagationFlags } |
        Sort-Object
}

$adPath = 'AD:' + $TargetDN
$acl = Get-Acl -Path $adPath
$currentSddl = $acl.GetSecurityDescriptorSddlForm([System.Security.AccessControl.AccessControlSections]::Access)

if (-not $IgnoreChanges -and (Get-Sha256Hex $currentSddl) -ne $ExpectedSha256) {
    throw 'The permissions on this object changed since Merkit read them. Re-run Merkit and generate a new script, or use -IgnoreChanges if you reviewed the current state.'
}

New-Item -ItemType Directory -Path $BackupDir -Force | Out-Null
$backupFile = Join-Path $BackupDir ('{0}_{1}.sddl' -f (Get-Date -Format 'yyyyMMdd_HHmmss'), ($TargetDN -replace '[^A-Za-z0-9]', '_'))
Set-Content -Path $backupFile -Value $currentSddl -Encoding UTF8
if ((Get-Content -Path $backupFile -Raw -Encoding UTF8).Trim() -ne $currentSddl.Trim()) { throw 'Backup verification failed. Nothing was changed.' }
Write-Host ""Backup written: $backupFile"" -ForegroundColor Green

if (-not $PSCmdlet.ShouldProcess($TargetDN, 'Replace DACL')) { return }

try {
    $new = Get-Acl -Path $adPath
    $new.SetSecurityDescriptorSddlForm($DesiredSddl, [System.Security.AccessControl.AccessControlSections]::Access)
    Set-Acl -Path $adPath -AclObject $new

    $after = (Get-Acl -Path $adPath).GetSecurityDescriptorSddlForm([System.Security.AccessControl.AccessControlSections]::Access)
    $diff = Compare-Object (Get-ExplicitRules $after) (Get-ExplicitRules $DesiredSddl)
    if ($diff) { throw 'Read-back does not match the requested permissions.' }
    Write-Host 'DACL updated and verified.' -ForegroundColor Green
}
catch {
    Write-Warning ""Failed: $($_.Exception.Message) - restoring backup...""
    $restore = Get-Acl -Path $adPath
    $restore.SetSecurityDescriptorSddlForm($currentSddl, [System.Security.AccessControl.AccessControlSections]::Access)
    Set-Acl -Path $adPath -AclObject $restore
    Write-Warning ""Original permissions restored. Backup file: $backupFile""
    throw
}
";

    private const string CsTemplate = @"// Applies a prepared Active Directory DACL. Generated by Merkit on __GENERATED__.
// Changes in this program:
__SUMMARY__
//
// Safeguards: stops if the object changed since Merkit read it, writes a backup first, verifies the result
// and restores the backup automatically on failure. Only the DACL is written.
// Build: dotnet new console; dotnet add package System.DirectoryServices; paste this as Program.cs.
// Uses the signed-in Windows identity (Kerberos). Run with --apply to write; without it, it only checks.

using System.DirectoryServices;
using System.Security.AccessControl;
using System.Security.Cryptography;
using System.Text;

const string TargetDn = ""__OU_DN__"";
const string ExpectedSha256 = ""__SHA__"";
const string DesiredSddl = ""__SDDL__"";

bool apply = args.Contains(""--apply"");
string backupDir = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData), ""Merkit"", ""Backups"");

static string Sha256Hex(string s) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(s))).ToLowerInvariant();

static DirectoryEntry Open(string dn)
{
    var entry = new DirectoryEntry($""LDAP://{dn}"");
    entry.Options.SecurityMasks = SecurityMasks.Dacl;
    return entry;
}

static string ReadSddl(string dn)
{
    using var entry = Open(dn);
    entry.RefreshCache();
    return entry.ObjectSecurity.GetSecurityDescriptorSddlForm(AccessControlSections.Access);
}

static void WriteSddl(string dn, string sddl)
{
    using var entry = Open(dn);
    var sec = new System.DirectoryServices.ActiveDirectorySecurity();
    sec.SetSecurityDescriptorSddlForm(sddl, AccessControlSections.Access);
    entry.ObjectSecurity = sec;
    entry.CommitChanges();
}

static string[] ExplicitRules(string sddl)
{
    var sec = new System.DirectoryServices.ActiveDirectorySecurity();
    sec.SetSecurityDescriptorSddlForm(sddl, AccessControlSections.Access);
    return sec.GetAccessRules(true, false, typeof(System.Security.Principal.SecurityIdentifier))
        .Cast<System.DirectoryServices.ActiveDirectoryAccessRule>()
        .Select(r => $""{r.IdentityReference.Value}|{r.AccessControlType}|{(int)r.ActiveDirectoryRights}|{r.InheritanceType}|{r.ObjectType}|{r.InheritedObjectType}|{r.PropagationFlags}"")
        .OrderBy(x => x, StringComparer.Ordinal).ToArray();
}

string current = ReadSddl(TargetDn);
if (Sha256Hex(current) != ExpectedSha256)
{
    Console.Error.WriteLine(""The permissions changed since Merkit read them. Generate a new script."");
    return 2;
}

Directory.CreateDirectory(backupDir);
string backupFile = Path.Combine(backupDir, $""{DateTime.Now:yyyyMMdd_HHmmss}_{new string(TargetDn.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray())}.sddl"");
File.WriteAllText(backupFile, current, Encoding.UTF8);
if (File.ReadAllText(backupFile, Encoding.UTF8) != current) { Console.Error.WriteLine(""Backup verification failed. Nothing changed.""); return 3; }
Console.WriteLine($""Backup written: {backupFile}"");

if (!apply) { Console.WriteLine(""Check only. Re-run with --apply to write.""); return 0; }

try
{
    WriteSddl(TargetDn, DesiredSddl);
    string after = ReadSddl(TargetDn);
    if (!ExplicitRules(after).SequenceEqual(ExplicitRules(DesiredSddl)))
        throw new InvalidOperationException(""Read-back does not match the requested permissions."");
    Console.WriteLine(""DACL updated and verified."");
    return 0;
}
catch (Exception ex)
{
    Console.Error.WriteLine($""Failed: {ex.Message} - restoring backup..."");
    WriteSddl(TargetDn, current);
    Console.Error.WriteLine($""Original permissions restored. Backup file: {backupFile}"");
    return 1;
}
";
}
